/* me1000_it.c —— 中断服务程序都写在这里（行业里对应 stm32f4xx_it.c）
 *
 * 为什么单独一个文件？因为启动文件里已经把所有处理函数声明成 weak 了，
 * 谁要用谁在这里定义一个同名函数就自动顶替，启动文件一个字都不用改。
 * 这套"启动文件 / 中断服务程序 / 业务代码"三分，是各家 SDK 的固定套路：
 *
 *     startup_xxx.s   谁都不是的公共地基，不该为了你的应用而改
 *     xxx_it.c        你占用的那些中断入口，集中一处便于查重和排查
 *     main.c + 业务    真正常变的东西
 *
 * 本工程的 main 是纯轮询点灯，没有开任何中断，所以下面这些函数目前不会被调用。
 * 它们的作用是"占好位置"，让你知道下一步该往哪儿写。
 */
#include "me1000.h"

/* ==================================================================
 * 一、内核异常：Cortex-M 内核自己的，编号 -14 ~ -1
 * ================================================================== */

/* HardFault：程序跑飞（空指针、数组越界、除零、栈溢出……）最后都掉这里。
 * 这里死等，是为了让调试器接上来时 PC 还停在现场，能看出是谁干的 ——
 * 换成"复位重来"你就会永远查不到问题。
 * 工程里通常还会在这里把 SCB 的故障状态寄存器和栈上压着的那几个寄存器
 * 转存到一个固定的 RAM 地址（."core dump"），事后慢慢分析。 */
void HardFault_Handler(void)
{
    for (;;) {
    }
}

/* SysTick：内核自带的定时器，裸机的时间基准（延时、超时、调度都靠它）。
 * 真接上它需要三步：写重装载值 -> 清当前值 -> 开中断并使能。
 * 接上之后，main 里那种空转延时就可以删掉了。
 *
 * 这个计数器放在这里、由中断改，主循环读，所以必须 volatile：
 * 否则编译器会认为"循环里没人改它"，把判断优化成死循环。 */
volatile uint32_t g_tick_ms;

void SysTick_Handler(void)
{
    g_tick_ms++;
}

